#!/usr/bin/env bash
# Turn the LLM credentials in .env into Sitewright configuration, without printing them.
#
#   scripts/dev-secrets.sh local   # writes dev/data/config.toml and dev/data/secrets.toml
#   scripts/dev-secrets.sh vps     # writes secrets.toml and the [llm] section on the dev VPS
#
# .env (git-ignored) must define AZURE_OPENAI_BASE_URL, AZURE_OPENAI_API_KEY and
# AZURE_OPENAI_DEPLOYMENT. Optional: ANTHROPIC_API_KEY, GEMINI_API_KEY.
set -euo pipefail
cd "$(dirname "$0")/.."
umask 077

[ -f .env ] || { echo "error: .env not found" >&2; exit 1; }
set -a
# shellcheck disable=SC1091
. ./.env
set +a
: "${AZURE_OPENAI_BASE_URL:?missing in .env}" "${AZURE_OPENAI_API_KEY:?missing in .env}" "${AZURE_OPENAI_DEPLOYMENT:?missing in .env}"

# TOML basic strings: escape backslashes and double quotes.
toml_str() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

secrets_toml() {
  echo '[keys]'
  printf 'azure = "%s"\n' "$(toml_str "$AZURE_OPENAI_API_KEY")"
  [ -n "${ANTHROPIC_API_KEY:-}" ] && printf 'anthropic = "%s"\n' "$(toml_str "$ANTHROPIC_API_KEY")"
  [ -n "${GEMINI_API_KEY:-}" ] && printf 'gemini = "%s"\n' "$(toml_str "$GEMINI_API_KEY")"
  return 0
}

llm_toml() {
  cat <<TOML

# --- generated by scripts/dev-secrets.sh from .env ---
[llm]
default = "azure"

[[llm.providers]]
id = "azure"
kind = "openai_compat"
base_url = "$(toml_str "$AZURE_OPENAI_BASE_URL")"
model = "$(toml_str "$AZURE_OPENAI_DEPLOYMENT")"
auth = "api_key_header"
key_ref = "azure"

# Prices are yours to edit: US dollars per million tokens for the deployment above.
[[llm.prices]]
model = "$(toml_str "$AZURE_OPENAI_DEPLOYMENT")"
input_per_mtok = 0.25
output_per_mtok = 2.00

[agent]
daily_spend_cap_usd = 5.0
TOML
}

case "${1:-}" in
  local)
    mkdir -p dev/data
    { grep -v '^data_dir' dev/local.toml; llm_toml; } > dev/data/config.toml
    secrets_toml > dev/data/secrets.toml
    chmod 600 dev/data/secrets.toml
    echo "wrote dev/data/config.toml and dev/data/secrets.toml"
    echo "run:  cargo run -- serve --data-dir dev/data"
    ;;
  vps)
    HOST="${SW_DEV_HOST:-racknerd-dev}"
    SSH="ssh -o BatchMode=yes -o ConnectTimeout=20 $HOST"
    $SSH 'mkdir -p ~/sitewright-data && chmod 700 ~/sitewright-data'
    secrets_toml | $SSH 'umask 077; cat > ~/sitewright-data/secrets.toml && chmod 600 ~/sitewright-data/secrets.toml'
    if $SSH 'grep -q "^\[llm\]" ~/sitewright-data/config.toml 2>/dev/null'; then
      echo "the VPS config already has an [llm] section; left as it is"
    else
      llm_toml | $SSH 'cat >> ~/sitewright-data/config.toml'
      echo "appended the [llm] section to the VPS config"
    fi
    $SSH 'export XDG_RUNTIME_DIR=/run/user/$(id -u); systemctl --user restart sitewright && systemctl --user is-active sitewright'
    echo "wrote secrets.toml on $HOST"
    ;;
  *)
    sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
